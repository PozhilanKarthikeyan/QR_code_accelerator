#!/usr/bin/env python3
"""Generate tables.py from the supplied QRTables.bsv.

The model must use exactly the tables the graders use, so instead of retyping
them we parse the BSV file.  Usage:

    python3 gen_tables.py path/to/QRTables.bsv > tables.py
"""
import re
import sys


def main(path):
    src = open(path).read()

    # blockParams:  8'd5: p = BlockParams { ecLen: 7, n1: 1, ... };  // 1-L
    blk = {}
    pat = re.compile(
        r"8'd(\d+):\s*p\s*=\s*BlockParams\s*\{\s*ecLen:\s*(\d+),\s*n1:\s*(\d+),"
        r"\s*d1:\s*(\d+),\s*n2:\s*(\d+),\s*nb:\s*(\d+),\s*totalData:\s*(\d+),"
        r"\s*total:\s*(\d+)\s*\}")
    for m in pat.finditer(src):
        key, ec, n1, d1, n2, nb, td, tot = map(int, m.groups())
        version, level = key >> 2, key & 3          # key = {version, levelField}
        blk[(version, level)] = (ec, n1, d1, n2, nb, td, tot)
    assert len(blk) == 160, len(blk)

    # alignParams:  N: begin n = 2; p = 56'h...; end  // [6, 18]
    aln = {}
    pat = re.compile(r"(\d+):\s*begin\s*n\s*=\s*(\d+);.*?//\s*\[([^\]]*)\]")
    for m in pat.finditer(src):
        v = int(m.group(1))
        lst = [int(x) for x in m.group(3).split(",") if x.strip()]
        assert len(lst) == int(m.group(2))
        aln[v] = lst
    assert len(aln) == 40, len(aln)

    # formatCodeword
    m = re.search(r"Integer t\[32\]\s*=\s*\{([^}]*)\}", src)
    fmt = [int(x) for x in m.group(1).split(",")]
    assert len(fmt) == 32

    out = []
    out.append('"""AUTO-GENERATED by gen_tables.py from QRTables.bsv -- do not edit."""')
    out.append("")
    out.append("# (version, levelField) -> (ecLen, n1, d1, n2, nb, totalData, total)")
    out.append("# levelField: 1 = L, 0 = M, 3 = Q, 2 = H")
    out.append("BLOCKS = {")
    for k in sorted(blk):
        out.append(f"    {k}: {blk[k]},")
    out.append("}")
    out.append("")
    out.append("# version -> alignment-pattern centre coordinates (rows and columns)")
    out.append("ALIGN = {")
    for k in sorted(aln):
        out.append(f"    {k}: {aln[k]},")
    out.append("}")
    out.append("")
    out.append("# 32 valid 15-bit format words, index = {level(2), mask(3)}")
    out.append(f"FORMAT_CODEWORDS = {fmt}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
